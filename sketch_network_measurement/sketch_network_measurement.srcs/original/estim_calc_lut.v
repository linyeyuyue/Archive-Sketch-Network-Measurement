        lut[43] = 16'h00a1; // 1/(64*ln(64/43)) = 0.039290
        lut[44] = 16'h00ab; // 1/(64*ln(64/44)) = 0.041701
        lut[45] = 16'h00b6; // 1/(64*ln(64/45)) = 0.044361
        lut[46] = 16'h00c2; // 1/(64*ln(64/46)) = 0.047314
