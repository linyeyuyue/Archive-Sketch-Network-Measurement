        lut[63] = 16'h0fe0; // 1/(64*ln(64/63)) = 0.992167
    end
    
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            inv_n_value <= 16'h0000;
        end else begin
            if (valid_i) begin
                // 查找表查询
                inv_n_value <= lut[zero_estim];
            end
        end
    end
endmodule
