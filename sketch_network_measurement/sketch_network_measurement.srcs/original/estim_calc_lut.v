);

    reg [15:0] lut [0:63];
    
    // 查找表初始化
    initial begin
        lut[0] = 16'h0000; // 1/(64*ln(64/1)) = 0.000000
        lut[1] = 16'h000f; // 1/(64*ln(64/1)) = 0.003757
        lut[2] = 16'h0012; // 1/(64*ln(64/2)) = 0.004508
        lut[3] = 16'h0015; // 1/(64*ln(64/3)) = 0.005106
