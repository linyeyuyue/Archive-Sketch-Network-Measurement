        lut[19] = 16'h0035; // 1/(64*ln(64/19)) = 0.012866
        lut[20] = 16'h0037; // 1/(64*ln(64/20)) = 0.013433
        lut[21] = 16'h0039; // 1/(64*ln(64/21)) = 0.014021
        lut[22] = 16'h003c; // 1/(64*ln(64/22)) = 0.014632
        lut[23] = 16'h003f; // 1/(64*ln(64/23)) = 0.015268
        lut[24] = 16'h0041; // 1/(64*ln(64/24)) = 0.015930
        lut[25] = 16'h0044; // 1/(64*ln(64/25)) = 0.016622
        lut[26] = 16'h0047; // 1/(64*ln(64/26)) = 0.017346
        lut[27] = 16'h004a; // 1/(64*ln(64/27)) = 0.018104
        lut[28] = 16'h004d; // 1/(64*ln(64/28)) = 0.018901
        lut[29] = 16'h0051; // 1/(64*ln(64/29)) = 0.019739
        lut[30] = 16'h0054; // 1/(64*ln(64/30)) = 0.020622
        lut[31] = 16'h0058; // 1/(64*ln(64/31)) = 0.021555
        lut[32] = 16'h005c; // 1/(64*ln(64/32)) = 0.022542
        lut[33] = 16'h0061; // 1/(64*ln(64/33)) = 0.023589
