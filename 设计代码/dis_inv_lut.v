module dis_inv_lut(
    input wire clk,                 // 时钟
    input wire rst_n,               // 异步低电平复位
    input wire [5:0] dis,           // 输入：6位活性跨度
    input wire valid_i,             // 输入有效信号
    output reg [15:0] inv_value     // 输出：1/dis的Q4.12定点值
);

    reg [15:0] inv_lut [1:64];
    
    // 查找表初始化
    initial begin
        inv_lut[1] = 16'h1000;   // 1/1 = 1.0000
        inv_lut[2] = 16'h0800;   // 1/2 = 0.5000
        inv_lut[3] = 16'h0555;   // 1/3 = 0.3333
        inv_lut[4] = 16'h0400;   // 1/4 = 0.2500
        inv_lut[5] = 16'h0333;   // 1/5 = 0.2000
        inv_lut[6] = 16'h02ab;   // 1/6 = 0.1667
        inv_lut[7] = 16'h0249;   // 1/7 = 0.1429
        inv_lut[8] = 16'h0200;   // 1/8 = 0.1250
        inv_lut[9] = 16'h01c7;   // 1/9 = 0.1111
        inv_lut[10] = 16'h019a;   // 1/10 = 0.1000
        inv_lut[11] = 16'h0174;   // 1/11 = 0.0909
        inv_lut[12] = 16'h0155;   // 1/12 = 0.0833
        inv_lut[13] = 16'h013b;   // 1/13 = 0.0769
        inv_lut[14] = 16'h0125;   // 1/14 = 0.0714
        inv_lut[15] = 16'h0111;   // 1/15 = 0.0667
        inv_lut[16] = 16'h0100;   // 1/16 = 0.0625
        inv_lut[17] = 16'h00f1;   // 1/17 = 0.0588
        inv_lut[18] = 16'h00e4;   // 1/18 = 0.0556
        inv_lut[19] = 16'h00d8;   // 1/19 = 0.0526
        inv_lut[20] = 16'h00cd;   // 1/20 = 0.0500
        inv_lut[21] = 16'h00c3;   // 1/21 = 0.0476
        inv_lut[22] = 16'h00ba;   // 1/22 = 0.0455
        inv_lut[23] = 16'h00b2;   // 1/23 = 0.0435
        inv_lut[24] = 16'h00ab;   // 1/24 = 0.0417
        inv_lut[25] = 16'h00a4;   // 1/25 = 0.0400
        inv_lut[26] = 16'h009e;   // 1/26 = 0.0385
        inv_lut[27] = 16'h0098;   // 1/27 = 0.0370
        inv_lut[28] = 16'h0092;   // 1/28 = 0.0357
        inv_lut[29] = 16'h008d;   // 1/29 = 0.0345
        inv_lut[30] = 16'h0089;   // 1/30 = 0.0333
        inv_lut[31] = 16'h0084;   // 1/31 = 0.0323
        inv_lut[32] = 16'h0080;   // 1/32 = 0.0312
        inv_lut[33] = 16'h007c;   // 1/33 = 0.0303
        inv_lut[34] = 16'h0078;   // 1/34 = 0.0294
        inv_lut[35] = 16'h0075;   // 1/35 = 0.0286
        inv_lut[36] = 16'h0072;   // 1/36 = 0.0278
        inv_lut[37] = 16'h006f;   // 1/37 = 0.0270
        inv_lut[38] = 16'h006c;   // 1/38 = 0.0263
        inv_lut[39] = 16'h0069;   // 1/39 = 0.0256
        inv_lut[40] = 16'h0066;   // 1/40 = 0.0250
        inv_lut[41] = 16'h0064;   // 1/41 = 0.0244
        inv_lut[42] = 16'h0062;   // 1/42 = 0.0238
        inv_lut[43] = 16'h005f;   // 1/43 = 0.0233
        inv_lut[44] = 16'h005d;   // 1/44 = 0.0227
        inv_lut[45] = 16'h005b;   // 1/45 = 0.0222
        inv_lut[46] = 16'h0059;   // 1/46 = 0.0217
        inv_lut[47] = 16'h0057;   // 1/47 = 0.0213
        inv_lut[48] = 16'h0055;   // 1/48 = 0.0208
        inv_lut[49] = 16'h0054;   // 1/49 = 0.0204
        inv_lut[50] = 16'h0052;   // 1/50 = 0.0200
        inv_lut[51] = 16'h0050;   // 1/51 = 0.0196
        inv_lut[52] = 16'h004f;   // 1/52 = 0.0192
        inv_lut[53] = 16'h004d;   // 1/53 = 0.0189
        inv_lut[54] = 16'h004c;   // 1/54 = 0.0185
        inv_lut[55] = 16'h004a;   // 1/55 = 0.0182
        inv_lut[56] = 16'h0049;   // 1/56 = 0.0179
        inv_lut[57] = 16'h0048;   // 1/57 = 0.0175
        inv_lut[58] = 16'h0047;   // 1/58 = 0.0172
        inv_lut[59] = 16'h0045;   // 1/59 = 0.0169
        inv_lut[60] = 16'h0044;   // 1/60 = 0.0167
        inv_lut[61] = 16'h0043;   // 1/61 = 0.0164
        inv_lut[62] = 16'h0042;   // 1/62 = 0.0161
        inv_lut[63] = 16'h0041;   // 1/63 = 0.0159
        inv_lut[64] = 16'h0040;   // 1/64 = 0.0156
    end
    
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            inv_value <= 16'h0000;
        end else begin
            if (valid_i) begin
                // 查找表查询
                inv_value <= inv_lut[dis];
            end
        end
    end
endmodule
